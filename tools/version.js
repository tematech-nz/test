'use strict';
/*
 * Source version: a short hash of every file the browser loads (index.html, css/*.css, js/*.js except js/version.js).
 *   node tools/version.js          write version.json and js/version.js
 *   node tools/version.js --check  exit 1 when they are stale
 * The page knows its own version from js/version.js and polls version.json to learn when the deployed code changed.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function sources(root) {
  const out = ['index.html'];
  ['css', 'js'].forEach((dir) => {
    fs.readdirSync(path.join(root, dir)).sort().forEach((f) => {
      if (dir === 'js' && f === 'version.js') return;
      if (/\.(js|css)$/.test(f)) out.push(dir + '/' + f);
    });
  });
  return out;
}
function computeVersion(root) {
  const h = crypto.createHash('sha1');
  sources(root).forEach((f) => {
    h.update(f + '\n');
    h.update(fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n'));
    h.update('\n');
  });
  return h.digest('hex').slice(0, 10);
}
function files(root, version) {
  return {
    'version.json': JSON.stringify({ version: version }) + '\n',
    'js/version.js': '/* generated by tools/version.js - do not edit */\nwindow.NetMap = window.NetMap || {};\nNetMap.version = "' + version + '";\n'
  };
}
function read(root, rel) { try { return fs.readFileSync(path.join(root, rel), 'utf8'); } catch (e) { return null; } }
function isCurrent(root) {
  const v = computeVersion(root), want = files(root, v);
  return Object.keys(want).every((rel) => read(root, rel) === want[rel]);
}
function write(root) {
  const v = computeVersion(root), want = files(root, v);
  Object.keys(want).forEach((rel) => { if (read(root, rel) !== want[rel]) fs.writeFileSync(path.join(root, rel), want[rel]); });
  return v;
}

module.exports = { computeVersion: computeVersion, isCurrent: isCurrent, write: write, sources: sources };

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  if (process.argv.includes('--check')) {
    if (isCurrent(root)) console.log('version files are current: ' + computeVersion(root));
    else { console.error('version.json / js/version.js are stale: run "npm run stamp"'); process.exit(1); }
  } else console.log('version ' + write(root));
}
